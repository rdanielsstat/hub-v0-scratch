const fields = (
  definitions: Array<
    [
      string,
      string,
      CollectionSchema['fields'][number]['type'],
      string?,
      string[]?,
    ]
  >,
) =>
  definitions.map(([id, name, type, unit, options], order) => ({
    id,
    name,
    type,
    unit,
    options,
    order,
  }))

